drop policy if exists produtos_leitura on storage.objects;
drop policy if exists produtos_envio   on storage.objects;
drop policy if exists produtos_troca   on storage.objects;
drop policy if exists produtos_remocao on storage.objects;

create policy produtos_leitura on storage.objects
  for select to anon, authenticated using (bucket_id = 'produtos');
create policy produtos_envio on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'produtos');
create policy produtos_troca on storage.objects
  for update to anon, authenticated using (bucket_id = 'produtos') with check (bucket_id = 'produtos');
create policy produtos_remocao on storage.objects
  for delete to anon, authenticated using (bucket_id = 'produtos');

-- ---------------------------------------------------------------------
-- 12. Acesso às tabelas
--
-- A API (Vercel) e o navegador falam com o banco pela chave anon, então
-- ela precisa ler e gravar em tudo. Mesma postura do sistema antigo.
--
-- Para fechar melhor depois: cadastre SUPABASE_SERVICE_ROLE_KEY na Vercel
-- (a API já prefere essa chave quando existe) e troque as policies abaixo
-- deixando o anon só com leitura do catálogo e INSERT de pedido.
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array[
    'users','products','clients','sales','sale_items','stock_movements',
    'fixed_costs','expenses','cash_sessions','cash_movements','settings',
    'orders','order_items','kits','kit_itens','migrations_aplicadas'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I_tudo on public.%I', t, t);
    execute format(
      'create policy %I_tudo on public.%I for all to anon, authenticated using (true) with check (true)',
      t, t);
  end loop;
end $$;

