-- ---------------------------------------------------------------------
-- 1. Usuários do sistema (PDV e painel usam a mesma tabela)
-- ---------------------------------------------------------------------
create table if not exists public.users (
  id         bigint generated by default as identity primary key,
  nome       text        not null,
  login      text        not null unique,
  senha_hash text        not null,              -- sha256 em hex
  role       text        not null default 'operador',   -- admin | operador
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 2. Produtos
--
-- Ração se vende por kg (preco_por_kg) ou saco fechado (preco_saco_fechado
-- + peso_saco_kg), estoque em kg. Outras categorias (sachê, petisco,
-- acessório...) se vendem por unidade (preco_unitario), estoque em unidade.
-- ---------------------------------------------------------------------
create table if not exists public.products (
  id                     bigint generated by default as identity primary key,
  nome                   text    not null,
  marca                  text    not null default '',
  tipo                   text    not null default 'cao',     -- cao | gato | filhote | castrado | outros
  categoria              text    not null default 'racao',   -- racao | sache | petisco | acessorio | higiene | medicamento | outros

  -- ração (kg)
  peso_saco_kg           numeric not null default 0,
  custo_saco             numeric not null default 0,
  custo_por_kg           numeric not null default 0,
  margem_percentual      numeric not null default 0,
  margem_saco            numeric not null default 0,
  preco_por_kg           numeric not null default 0,
  preco_saco_fechado     numeric not null default 0,
  estoque_kg             numeric not null default 0,
  estoque_minimo_dias    integer not null default 7,

  -- unidade
  custo_unitario         numeric not null default 0,
  preco_unitario         numeric not null default 0,
  estoque_unidade        integer not null default 0,
  estoque_minimo_unidade integer not null default 0,

  -- loja online
  especie                text,            -- cao | gato | null (serve os dois)
  porte                  text,            -- pequena | media | grande | null
  perfil                 text,            -- filhote | adulto | castrado | senior | null
  foto_url               text,
  visivel_loja           boolean not null default false,
  vende_fracionado       boolean not null default true,
  promo_qtd              integer,         -- "leve 4"
  promo_preco            numeric,         -- "por R$ 12"

  ativo                  integer not null default 1,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);

alter table public.products drop constraint if exists products_promo_coerente;
alter table public.products add constraint products_promo_coerente check (
  (promo_qtd is null and promo_preco is null)
  or (promo_qtd >= 2 and promo_preco > 0)
);

create index if not exists products_ativo_idx     on public.products (ativo);
create index if not exists products_categoria_idx on public.products (categoria);
create index if not exists products_especie_idx   on public.products (especie);

-- ---------------------------------------------------------------------
-- 3. Clientes
-- ---------------------------------------------------------------------
create table if not exists public.clients (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  whatsapp        text not null default '',
  tipo_pet        text not null default '',
  racao_utilizada text not null default '',
  ultima_compra   timestamptz,
  created_at      timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 4. Vendas do PDV
-- ---------------------------------------------------------------------
create table if not exists public.sales (
  id              bigint generated by default as identity primary key,
  client_id       bigint references public.clients(id) on delete set null,
  total           numeric not null default 0,
  desconto        numeric not null default 0,
  forma_pagamento text    not null default 'dinheiro',  -- dinheiro | pix | debito | credito | fiado
  created_at      timestamptz not null default now()
);

-- quantidade_kg guarda a quantidade na unidade do tipo_venda:
--   'kg' -> quilos | 'saco' -> sacos fechados | 'unidade' -> unidades
create table if not exists public.sale_items (
  id             bigint generated by default as identity primary key,
  sale_id        bigint not null references public.sales(id) on delete cascade,
  product_id     bigint not null references public.products(id) on delete restrict,
  tipo_venda     text    not null default 'kg',
  quantidade_kg  numeric not null default 0,
  preco_unitario numeric not null default 0,
  subtotal       numeric not null default 0
);

create index if not exists sales_created_at_idx   on public.sales (created_at desc);
create index if not exists sales_client_idx       on public.sales (client_id);
create index if not exists sale_items_sale_idx    on public.sale_items (sale_id);
create index if not exists sale_items_product_idx on public.sale_items (product_id);

-- ---------------------------------------------------------------------
-- 5. Movimentações de estoque
-- ---------------------------------------------------------------------
create table if not exists public.stock_movements (
  id            bigint generated by default as identity primary key,
  product_id    bigint not null references public.products(id) on delete restrict,
  tipo          text    not null default 'entrada',   -- entrada | saida | ajuste
  quantidade_kg numeric not null default 0,
  motivo        text    not null default '',
  sale_id       bigint references public.sales(id) on delete set null,
  created_at    timestamptz not null default now()
);

create index if not exists stock_movements_product_idx on public.stock_movements (product_id);
create index if not exists stock_movements_created_idx on public.stock_movements (created_at desc);

-- ---------------------------------------------------------------------
-- 6. Financeiro: custos fixos e despesas
-- ---------------------------------------------------------------------
create table if not exists public.fixed_costs (
  id         bigint generated by default as identity primary key,
  descricao  text    not null,
  valor      numeric not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.expenses (
  id               bigint generated by default as identity primary key,
  descricao        text    not null,
  categoria        text    not null default 'outros',
  valor            numeric not null default 0,
  data_vencimento  date,
  pago             integer not null default 0,
  data_pagamento   date,
  recorrente       integer not null default 0,
  data_inicio      date,
  data_fim         date,
  tipo_recorrencia text    not null default 'nenhum',   -- nenhum | mensal | semanal
  created_at       timestamptz not null default now()
);

create index if not exists expenses_vencimento_idx on public.expenses (data_vencimento);

-- ---------------------------------------------------------------------
-- 7. Caixa
-- ---------------------------------------------------------------------
create table if not exists public.cash_sessions (
  id                    bigint generated by default as identity primary key,
  saldo_inicial         numeric not null default 0,
  saldo_final           numeric,
  status                text    not null default 'aberto',   -- aberto | fechado
  observacao_fechamento text,
  opened_at             timestamptz not null default now(),
  closed_at             timestamptz
);

create table if not exists public.cash_movements (
  id         bigint generated by default as identity primary key,
  session_id bigint not null references public.cash_sessions(id) on delete cascade,
  tipo       text    not null,                 -- abertura | venda | sangria | suprimento | fechamento
  valor      numeric not null default 0,
  descricao  text    not null default '',
  sale_id    bigint references public.sales(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists cash_movements_session_idx on public.cash_movements (session_id);

